export const initialLang = () => {
  try { const s = localStorage.getItem('rrq-lang'); if (s === 'en' || s === 'bn') return s; } catch { /* storage blocked */ }
  return /^bn/i.test(navigator.language || '') ? 'bn' : 'en';
};
export const saveLang = l => { try { localStorage.setItem('rrq-lang', l); } catch { /* storage blocked */ } };
