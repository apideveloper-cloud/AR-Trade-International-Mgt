export function Orders({ staff }) {
  const t = useTable('/orders', { status: '', source: '', pay: '', customer: '', product: '', ...monthRange(), min: '', max: '', summary: 1 });
  const [open, setOpen] = useState(null); const [create, setCreate] = useState(false);
  const counts = t.data.counts || {};
  const all = Object.values(counts).reduce((a, b) => a + b, 0);
  const rider = staff.role === 'Delivery rider';
  return (
    <>
      <div className="a-chips oc-bar">
        <button className={'a-chip' + (!t.params.status ? ' on' : '')} onClick={() => t.set({ status: '' })}>All · {all}</button>
        {STATUSES.map(s => <button key={s} className={'a-chip' + (t.params.status === s ? ' on' : '')} onClick={() => t.set({ status: s })}>{s} · {counts[s] || 0}</button>)}
        {can(staff, 'orders.create') && <button type="button" className="a-btn sm grad oc-new" onClick={() => setCreate(true)}>＋ New order</button>}
      </div>
      <div className="a-chips oc-src-bar" aria-label="Order generated by">
        <span className="oc-src-lbl">Generated by</span>
        <button className={'a-chip' + (!t.params.source ? ' on' : '')} onClick={() => t.set({ source: '' })}>Anyone</button>
        {SOURCES.map(s => <button key={s.key} className={'a-chip' + (t.params.source === s.key ? ' on' : '')} onClick={() => t.set({ source: s.key })}>{s.icon} {s.key}</button>)}
      </div>
      {t.data.summary && (() => {
        const m = t.data.summary;
        return <Summary items={[
          ['Orders', m.total, m.cancelled + ' cancelled', 'blue', 'cart'],
          ['Revenue', fmtMoney(m.revenue), 'Avg ' + fmtMoney(m.avg) + ' per order', 'green', 'money'],
          ['Today', m.today, fmtMoney(m.todayRevenue) + ' today', 'violet', 'clock'],
          ['Open orders', m.open, fmtMoney(m.openValue) + ' to deliver', 'amber', 'truck'],
          ['To collect', fmtMoney(m.unpaid), 'Unpaid, not cancelled', 'red', 'alert']
        ]} />;
      })()}
      <OrderSearch t={t} />
      <Toolbar t={t} />
      <div className="a-table ord" style={{ opacity: t.loading ? .6 : 1 }}>
        <div style={{ minWidth: 804 }}>
          <div className="head" style={{ gridTemplateColumns: '44px 100px minmax(160px,1fr) 120px 140px 120px 110px' }}><span>SL</span><span>Order</span><span>Customer</span><span>Date</span><span>Payment</span><span>Status</span><span style={{ textAlign: 'right' }}>Total</span></div>
          {t.data.rows.map((o, i) => (
            <button key={o.id} className="row" style={{ gridTemplateColumns: '44px 100px minmax(160px,1fr) 120px 140px 120px 110px' }} onClick={() => setOpen(o.id)}>
              <span className="sl">{slNo(t, i)}</span>
              <b>{o.id}</b>
              <span style={{ display: 'flex', flexDirection: 'column' }}><b style={{ fontWeight: 600 }}>{o.customer.name}</b><span style={{ color: '#5d6270', fontSize: 12 }}>{o.customer.phone} · {AREA[o.area]}{o.source && o.source !== 'Customer' && <i className={'oc-tag ' + (SOURCE_TONE[o.source] || '')}>{o.source}</i>}</span></span>
              <span style={{ color: '#5d6270' }}>{dateF(o.date)}</span><span>{o.payment}{o.payStatus === 'Paid' ? ' ✓' : ''}</span><Pill s={o.status} />
              <b style={{ textAlign: 'right' }}>{fmtMoney(o.total)}</b>
            </button>
          ))}
        </div>
      </div>
      <Empty t={t} /><Pager t={t} />
      {create && <OrderCreate staff={staff} onClose={() => setCreate(false)} onCreated={o => { t.reload(); setOpen(o.id); }} />}
      {open && <OrderDrawer id={open} riderOnly={rider} canDelete={!rider} onClose={() => setOpen(null)} onChanged={t.reload} />}
    </>
  );
}

export function Deliveries() {
  const t = useTable('/orders', { status: 'Packed,Shipped', queue: 1, q: '', product: '', area: '', pay: '', from: '', to: '', min: '', max: '', size: 25 });
  const [move, setMove] = useState(null); // { order, to }: the remarks dialog
  const [open, setOpen] = useState(null);
  const rows = t.data.rows;
  const counts = t.data.counts || {}, queue = t.data.queue || {};
  const reload = t.reload;
  const loading = t.loading && !rows.length;
  const filtered = ['q', 'product', 'area', 'pay', 'from', 'to', 'min', 'max'].some(k => t.params[k]);
  return (
    <>
      <Summary items={[
        ['Waiting for pickup', counts.Packed ?? 0, 'packed, ready to go', 'amber', 'box'],
        ['Out for delivery', counts.Shipped ?? 0, 'with a rider or courier', 'blue', 'truck'],
        ['COD to collect', fmtMoney(queue.cod), `${queue.codCount ?? 0} unpaid order${queue.codCount === 1 ? '' : 's'}`, 'red', 'money']
      ]} />
      <DeliverySearch lists={[t]} />
      <Toolbar t={t} search={false} />
      {t.error && <div className="a-msg err">{t.error}</div>}
      <section className="a-card dq">
        <div className="dq-hd">
          <div><b>Delivery queue</b><small>Pick up packed orders, then mark them delivered</small></div>
          <div className="a-chips">
            {[['Packed,Shipped', 'All', (counts.Packed ?? 0) + (counts.Shipped ?? 0)], ['Packed', 'Waiting for pickup', counts.Packed ?? 0], ['Shipped', 'Out for delivery', counts.Shipped ?? 0]].map(([k, l, n]) => <button key={k} type="button" className={'a-chip' + (t.params.status === k ? ' on' : '')} onClick={() => t.set({ status: k })}>{l} · {n}</button>)}
          </div>
        </div>
        {loading ? <span className="spin" style={{ margin: 20 }} /> : !rows.length ? (
          <div className="dq-empty"><span><svg viewBox="0 0 24 24"><path d="M3 6h11v10H3zM14 9h4l3 3v4h-7" /><circle cx="7.5" cy="17.5" r="1.8" /><circle cx="17.5" cy="17.5" r="1.8" /></svg></span><b>{filtered ? 'No delivery matches your search' : 'Nothing to deliver right now'}</b><small>{filtered ? 'Change or reset the filters above to see more.' : 'Orders appear here once they are packed. Set an order to Packed from the Orders page.'}</small></div>
        ) : rows.map(o => (
          <div key={o.id} className="dq-row" onClick={() => setOpen(o.id)}>
            <span className="dq-av" style={{ '--h': hueOf(o.customer.name) }}>{String(o.customer.name || '?').split(/\s+/).map(w => w[0]).slice(0, 2).join('').toUpperCase()}</span>
            <div className="dq-who"><b>{o.customer.name} <em className="mono">{o.id}</em></b><span>{o.address} · {AREA[o.area]}</span><small>{o.items.reduce((a, i) => a + i.qty, 0)} item(s){o.slot ? ' · ' + o.slot : ''}</small></div>
            <div className="dq-amt"><b>{fmtMoney(o.total)}</b><small className={o.payStatus === 'Paid' ? 'ok' : 'due'}>{o.payment} · {o.payStatus === 'Paid' ? 'Paid' : 'collect'}</small></div>
            <Pill s={o.status} />
            <div className="dq-act" onClick={e => e.stopPropagation()}>
              <a href={'tel:' + o.customer.phone} className="a-mini" title={o.customer.phone}>☎ Call</a>
              {o.status === 'Packed' && <button type="button" className="a-mini on" onClick={() => setMove({ order: o, to: 'Shipped' })}>Picked up</button>}
              {o.status === 'Shipped' && <button type="button" className="a-mini ok" onClick={() => setMove({ order: o, to: 'Delivered' })}>Mark delivered</button>}
            </div>
          </div>
        ))}
      </section>
      <Pager t={t} />
      {move && <StatusDialog id={move.order.id} from={move.order.status} to={move.to} onClose={() => setMove(null)} onSaved={() => { setMove(null); reload(); }} />}
      {open && <OrderDrawer id={open} riderOnly={false} canDelete={false} onClose={() => setOpen(null)} onChanged={reload} />}
    </>
  );
}

export function Customers() {
  const t = useTable('/customers', { from: '', to: '' });
  const [reqs, setReqs] = useState([]);
  const [link, setLink] = useState(null); // { name, url, phone }
  const [copied, setCopied] = useState(false);
  const loadReqs = () => adm.get('/password-resets').then(setReqs).catch(() => {});
  useEffect(() => { loadReqs(); }, []);
  const makeLink = async c => {
    try { const r = await adm.post(`/customers/${c.userId}/reset-link`); setLink({ name: c.name, phone: c.phone, url: window.location.origin + r.path, hours: r.hours }); loadReqs(); } catch (e) { alertBox(e.message); }
  };
  const [pwFor, setPwFor] = useState(null);
  const setPw = c => setPwFor(c);
  const [view, setView] = useState(null); // the customer whose details are open
  const cols = '44px minmax(180px,1fr) 140px 70px 110px 110px 84px';
  return (
    <>
      {pwFor && <SetPasswordModal c={pwFor} onClose={() => setPwFor(null)} onDone={loadReqs} />}
      {reqs.length > 0 && (
        <div className="a-card" style={{ background: 'oklch(0.97 0.03 85)', borderColor: 'oklch(0.9 0.06 85)' }}>
          <h3>🔑 Password reset requests ({reqs.length})</h3>
          {reqs.map(r => (
            <div key={r.id} style={{ display: 'flex', alignItems: 'center', gap: 12, flexWrap: 'wrap', padding: '6px 0', borderTop: '1px solid oklch(0.9 0.05 85)' }}>
              <span style={{ flex: 1, minWidth: 200 }}><b>{r.name}</b> · {r.phone} · {r.email}<br /><small style={{ color: '#6b7080' }}>asked {dateF(r.created)}</small></span>
              <button className="a-btn sm" onClick={() => makeLink({ userId: r.userId, name: r.name, phone: r.phone })}>Create reset link</button>
              <button className="a-btn ghost sm" onClick={async () => { await adm.del('/password-resets/' + r.id); loadReqs(); }}>Dismiss</button>
            </div>
          ))}
        </div>
      )}
      {link && (
        <Modal kicker="Password reset" title={'Reset link for ' + link.name} onClose={() => setLink(null)}
          footer={<>
            <button type="button" className="a-btn sm" onClick={() => { navigator.clipboard?.writeText(link.url); setCopied(true); setTimeout(() => setCopied(false), 2000); }}>{copied ? 'Copied ✓' : 'Copy link'}</button>
            <a className="a-btn ghost sm" target="_blank" rel="noreferrer" href={`https://wa.me/88${String(link.phone || '').replace(/\D/g, '')}?text=${encodeURIComponent('AR Trade: set a new password here (valid 24 hours): ' + link.url)}`}>Send on WhatsApp</a>
            <button type="button" className="a-btn ghost sm" onClick={() => setLink(null)}>Close</button>
          </>}>
          <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
            <span style={{ fontSize: 13, color: '#4b5263', lineHeight: 1.5 }}>Send this one-time link to <b>{link.name}</b>{link.phone ? ' (' + link.phone + ')' : ''}. It stays valid for <b>{link.hours} hours</b> and works once. The customer opens it and chooses a new password.</span>
            <input className="a-input" readOnly value={link.url} onFocus={e => e.target.select()} style={{ fontFamily: 'var(--mono)', fontSize: 12 }} />
          </div>
        </Modal>
      )}
      {t.data.summary && (() => {
        const m = t.data.summary, pct = (a, b) => (b ? Math.round(a / b * 100) : 0);
        return <Summary items={[
          ['Customers', m.total, m.accounts + ' with an online account', 'blue', 'users'],
          ['Buyers', m.buyers, pct(m.buyers, m.total) + '% have placed an order', 'green', 'check'],
          ['Lifetime revenue', fmtMoney(m.revenue), 'Avg ' + fmtMoney(m.avg) + ' per buyer', 'violet', 'money'],
          ['Repeat customers', m.repeat, pct(m.repeat, m.buyers) + '% of buyers ordered 2+ times', 'amber', 'repeat'],
          ['New accounts', m.newAccounts, 'Registered in the last 30 days', 'blue', 'plus'],
          ['Top customer', m.top ? m.top.name : '–', m.top ? fmtMoney(m.top.ltv) + ' lifetime' : 'No orders yet', 'amber', 'star']
        ]} />;
      })()}
      <ListFilter t={t} noun="customer" title="Search customers" search={{ placeholder: 'Name, phone or email' }} range={{ label: 'Last order' }} />
      <Toolbar t={t} search={false} />
      <div className="a-table" style={{ opacity: t.loading ? .6 : 1 }}>
        <div style={{ minWidth: 904 }}>
          <div className="head" style={{ gridTemplateColumns: cols }}><span>SL</span><span>Customer</span><span>Phone</span><span>Orders</span><span>Lifetime</span><span>Last order</span><span style={{ textAlign: 'right' }}>Password</span></div>
          {t.data.rows.map((c, i) => (
            <div key={c.phone + c.name} className="row cu-row" style={{ gridTemplateColumns: cols }} onClick={() => setView(c)} role="button" tabIndex={0} onKeyDown={e => { if (e.key === 'Enter') setView(c); }}>
              <span className="sl">{slNo(t, i)}</span>
              <span style={{ display: 'flex', flexDirection: 'column' }}><b>{c.name}</b><span style={{ color: '#5d6270', fontSize: 12 }}>{c.email}</span></span>
              <a href={'tel:' + c.phone}>{c.phone}</a><span>{c.n}</span><b>{fmtMoney(c.ltv)}</b><span style={{ color: '#5d6270' }}>{dateF(c.last)}</span>
              {c.userId ? <span className="cu-act" onClick={e => e.stopPropagation()}><button type="button" className="cu-ic" title="Reset link: create a one-time link the customer can use to choose a new password" aria-label="Create reset link" onClick={() => makeLink(c)}>{KEY_ICON}</button><button type="button" className="cu-ic" title="Set password: type a new password for this customer yourself" aria-label="Set password" onClick={() => setPw(c)}>{LOCK_ICON}</button></span> : <span style={{ color: '#8a8f9b', fontSize: 12, textAlign: 'right' }}>no account</span>}
            </div>
          ))}
        </div>
      </div>
      <Empty t={t} /><Pager t={t} />
      {view && <CustomerDrawer c={view} onClose={() => setView(null)} onReset={makeLink} onSetPassword={setPw} />}
    </>
  );
}

