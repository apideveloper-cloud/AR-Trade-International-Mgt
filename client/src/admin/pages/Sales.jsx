import { useEffect, useState } from 'react';
import { adm, can, dateF, fmtMoney, slNo, useTable } from '../adminApi.js';
import { Empty, Modal, Pager, Pill, Summary, Toolbar, alertBox, hueOf } from '../ui.jsx';
import { STATUSES, AREA } from './sales/constants.js';
import { OrderDrawer } from './sales/OrderDrawer.jsx';
import { OrderCreate } from './sales/OrderCreate.jsx';
import { SOURCES, SOURCE_TONE } from './sales/sources.js';
import { StatusDialog } from './sales/StatusDialog.jsx';
import { DeliverySearch } from './sales/DeliverySearch.jsx';
import { CustomerDrawer, KEY_ICON, LOCK_ICON } from './sales/CustomerDrawer.jsx';
